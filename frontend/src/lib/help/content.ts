/** 全文检索用的扁平条目 */
export function searchHelp(keyword: string): { title: string; text: string; anchor: string }[] {
  const q = keyword.trim().toLowerCase();
  if (!q) return [];
  const out: { title: string; text: string; anchor: string }[] = [];
  const push = (title: string, text: string, anchor: string) => {
    if (`${title} ${text}`.toLowerCase().includes(q)) out.push({ title, text, anchor });
  };
  for (const s of [...MANUAL.sections, ...SPEC.sections]) {
    push(s.title, [
      s.summary, s.keywords || '', ...(s.paragraphs || []), ...(s.bullets || []),
      ...(s.steps || []).map(x => x.text), s.note || '',
    ].join(' '), s.id);
  }
  for (const g of FAQ) for (const it of g.items) push(it.q, it.a, `faq-${g.id}`);
  for (const t of GLOSSARY) push(t.term, t.def, 'glossary');
  return out.slice(0, 12);
}
